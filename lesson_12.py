# Импортируем Pandas для работы с таблицами.
import pandas as pd
# Импортируем NumPy. Он нужен нам здесь только для одной цели — создать пустое значение np.nan (Not a Number).
import numpy as np 

# Создаем словарь с "грязными" данными (там, где np.nan, данных нет).
data = {
    "name": ["Алексей", "Лина", "Дмитрий", "Анастасия", "Иван", "Мария", "Петр"],
    "age": [23, 25, 22, 21, 24, 22, np.nan],  # У Петра вместо возраста стоит NaN
    "score": [4.5, 5.0, 3.8, np.nan, 3.5, 4.8, 4.0], # У Анастасии вместо оценки NaN
    "faculty": ["IT", "IT", "Math", "Math", "IT", "Physics", "Math"]
}
# Превращаем словарь в таблицу DataFrame.
df = pd.DataFrame(data)

# .isna() проверяет каждую ячейку: если там NaN, ставит True, иначе False.
# .sum() складывает все True. В итоге мы видим, сколько пропусков в каждой колонке.
print(df.isna().sum())

# Берем колонку "age". Метод .fillna() заполняет пустоты (NaN).
# Мы говорим: "Заполни пустоты средним значением этой же колонки (df["age"].mean())".
# И сохраняем результат обратно в колонку df["age"].
df["age"] = df["age"].fillna(df["age"].mean())

# Берем колонку "score" и заполняем пустоты нулем (0).
df["score"] = df["score"].fillna(0)
# Выводим очищенную таблицу. Теперь NaN нет.
print(df)

# ГРУППИРОВКА. .groupby("faculty") разбивает всех студентов на группы по факультету.
# ["score"] указывает, с какой колонкой мы будем работать внутри этих групп.
# .mean() считает среднее значение для каждой группы.
print(df.groupby("faculty")["score"].mean())

# МУЛЬТИ-АГРЕГАЦИЯ. .agg() позволяет применить сразу несколько функций.
# В словаре мы указываем колонку "score" и список функций: ["mean", "max", "count"].
# count — считает количество студентов (строк) в каждой группе.
print(df.groupby("faculty").agg({"score": ["mean", "max", "count"]}))