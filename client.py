# Импортируем библиотеку requests. Она нужна для отправки сетевых запросов (HTTP).
import requests

# Записываем адрес, куда будем стучаться. 
# 127.0.0.1 — это "локальный хост" (твой же компьютер). 8000 — порт, на котором работает uvicorn.
url = "http://127.0.0.1:8000/predict"

# Создаем словарь с данными (payload), которые хотим отправить.
# Ключи словаря должны ТОЧНО совпадать с теми полями, которые мы описали в классе FlowerFeatures в api_server.py.
data = {
    "sepal_length": 5.1,
    "sepal_width": 3.5,
    "petal_length": 1.4,
    "petal_width": 0.2
}

# Отправляем POST-запрос.
# url — куда отправляем.
# json=data — автоматически превращает наш словарь Python в строку формата JSON 
# и добавляет нужный заголовок Content-Type.
response = requests.post(url, json=data)

# Проверяем код ответа. 
# 200 — это стандартный код HTTP, означающий "ОК, успех". (404 — не найдено, 500 — ошибка сервера).
if response.status_code == 200:
    # Если успех, берем ответ от сервера и превращаем его из JSON-строки обратно в словарь Python.
    result = response.json()
    
    # Выводим результат, обращаясь к ключам словаря.
    print("Ответ от сервера:")
    print(f"Код: {result['prediction_code']}")
    print(f"Цветок: {result['flower_name']}")
else:
    # Если сервер вернул ошибку (например, мы забыли его запустить), выводим код ошибки.
    print(f"Ошибка сервера: {response.status_code}")